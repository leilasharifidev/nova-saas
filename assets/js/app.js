const languageToggle = document.getElementById("languageToggle");
const menuToggle = document.getElementById("menuToggle");
const navLinks = document.getElementById("navLinks");

function setLanguage(language) {
  const dictionary = translations[language];
  document.documentElement.lang = language;
  document.documentElement.dir = language === "fa" ? "rtl" : "ltr";
  document.body.dir = language === "fa" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key] !== undefined) element.innerHTML = dictionary[key];
  });

  languageToggle.textContent = language === "en" ? "FA" : "EN";
  languageToggle.setAttribute("aria-label", language === "en" ? "Switch to Persian" : "Switch to English");
  saveLanguage(language);
  const dateLabel = document.getElementById("currentDate");
  if (dateLabel) dateLabel.textContent = new Intl.DateTimeFormat(language === "fa" ? "fa-IR" : "en-US", { year: "numeric", month: "short", day: "numeric" }).format(new Date());
}

function getSavedLanguage() {
  try { return window.localStorage.getItem("nova-language"); }
  catch (error) { return null; }
}

function saveLanguage(language) {
  try { window.localStorage.setItem("nova-language", language); }
  catch (error) { /* Storage may be unavailable in restricted preview contexts. */ }
}

const savedLanguage = getSavedLanguage();
setLanguage(savedLanguage === "fa" ? "fa" : "en");

languageToggle.addEventListener("click", () => {
  const nextLanguage = document.documentElement.lang === "en" ? "fa" : "en";
  setLanguage(nextLanguage);
});

menuToggle.addEventListener("click", () => {
  const isOpen = navLinks.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(isOpen));
});

navLinks.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    navLinks.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
  });
});


// Apply editable customer settings and dynamic date/year labels.
const contactLink = document.querySelector('.contact-panel a[href^="mailto:"]');
const configuredEmail = window.NOVA_CONFIG?.contactEmail?.trim();
if (contactLink && configuredEmail) {
  contactLink.href = `mailto:${configuredEmail}`;
}

const currentYear = document.getElementById("currentYear");
if (currentYear) currentYear.textContent = String(new Date().getFullYear());

const currentDate = document.getElementById("currentDate");
if (currentDate) {
  currentDate.textContent = new Intl.DateTimeFormat(
    document.documentElement.lang === "fa" ? "fa-IR" : "en-US",
    { year: "numeric", month: "short", day: "numeric" }
  ).format(new Date());
}
